def build_schema(meta):
    return {
        "@context": "https://schema.org",
        "@type": "HowTo",
        "name": meta['name'],
        "description": meta['description'],
        "step": [
            {"@type": "HowToStep", "name": n, "text": t}
            for n, t in meta['steps']
        ],
    }


def has_howto(html):
    return '"@type": "HowTo"' in html or '"@type":"HowTo"' in html


def main():
    done, skipped = 0, 0
    for fname, meta in HOWTO.items():
        path = os.path.join(SITE_DIR, fname)
        if not os.path.exists(path):
            print(f'⚠️  找不到 {fname}')
            continue
        with open(path, encoding='utf-8') as fh:
            html = fh.read()
        if has_howto(html):
            skipped += 1
            continue
        schema = build_schema(meta)
        script = (
            '\n    <!-- AEO HowTo Schema -->\n'
            f'    <script type="application/ld+json">{json.dumps(schema, ensure_ascii=False)}</script>\n'
        )
        html = html.replace('</body>', script + '</body>')
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(html)
        done += 1
    print(f'✅ 已加上 HowTo schema: {done} 頁')
    print(f'⏭️  已有跳過: {skipped} 頁')


if __name__ == '__main__':
    main()
